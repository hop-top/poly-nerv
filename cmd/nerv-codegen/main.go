type PayloadField struct {
	Field string `yaml:"field"`
	Type  string `yaml:"type"`
}

type EventDef struct {
	Name            string         `yaml:"name"`
	Category        string         `yaml:"category"`
	Description     string         `yaml:"description"`
	Direction       string         `yaml:"direction"`
	Blocking        bool           `yaml:"blocking"`
	Payload         []PayloadField `yaml:"payload"`
	Origin          string         `yaml:"origin"`
	ExtensionSource string         `yaml:"extension_source"`
	Derivation      *Derivation    `yaml:"derivation,omitempty"`
}

// Derivation describes how a derived event is synthesized from a
// source native event. Only set when origin == "derived".
type Derivation struct {
	From string                 `yaml:"from"`
	When map[string]interface{} `yaml:"when"`
}

// EffectiveOrigin returns Origin or "native" when blank.
func (e EventDef) EffectiveOrigin() string {
	if e.Origin == "" {
		return "native"
	}
	return e.Origin
}

type Spec struct {
	Version     string     `yaml:"version"`
	Description string     `yaml:"description"`
	Events      []EventDef `yaml:"events"`
}

var tmplFuncs = template.FuncMap{
	// camel converts an event name to a Go-friendly PascalCase identifier
	// suffix. Already-PascalCase names pass through unchanged
	// (e.g. "SessionStart" → "SessionStart"); snake_case names are
	// upper-camelized (e.g. "inbox_message_added" → "InboxMessageAdded").
	"camel": camelize,
}

var tmpl = template.Must(template.New("events").
	Funcs(tmplFuncs).
	Parse(`// Code generated by nerv-codegen from spec/events.yaml; DO NOT EDIT.
// Generated at: {{ .Timestamp }}
// Source: spec/events.yaml ({{ .Version }})

package events

// Event represents a nerv hook event name.
type Event string

const (
{{- range .Events }}
	// Event{{ camel .Name }} — {{ .Description }}
	Event{{ camel .Name }} Event = "{{ .Name }}"
{{- end }}
)

// allEvents is the internal list of every registered event.
var allEvents = []Event{
{{- range .Events }}
	Event{{ camel .Name }},
{{- end }}
}

// categoryMap maps each event to its category.
var categoryMap = map[Event]string{
{{- range .Events }}
	Event{{ camel .Name }}: "{{ .Category }}",
{{- end }}
}

// blockingSet contains events that are blocking.
var blockingSet = map[Event]bool{
{{- range .Events }}
{{- if .Blocking }}
	Event{{ camel .Name }}: true,
{{- end }}
{{- end }}
}

// originMap maps each event to its origin: native | derived | extension.
var originMap = map[Event]string{
{{- range .Events }}
	Event{{ camel .Name }}: "{{ .EffectiveOrigin }}",
{{- end }}
}

// AllEvents returns a copy of every registered event.
func AllEvents() []Event {
	out := make([]Event, len(allEvents))
	copy(out, allEvents)
	return out
}

// IsValid reports whether e is a known event.
func IsValid(e Event) bool {
	_, ok := categoryMap[e]
	return ok
}

// Category returns the category string for a known event,
// or "" if the event is unknown.
func Category(e Event) string {
	return categoryMap[e]
}

// IsBlocking reports whether the event is blocking.
func IsBlocking(e Event) bool {
	return blockingSet[e]
}

// Origin returns the origin classification for a known event:
// "native", "derived", or "extension". Empty string for unknowns.
func Origin(e Event) string {
	return originMap[e]
}

// IsNative reports whether the event is emitted directly by a CLI
// adapter from the host CLI's lifecycle.
func IsNative(e Event) bool { return originMap[e] == "native" }

// IsDerived reports whether the event is synthesized by the
// dispatcher from a native event + filter/correlation.
func IsDerived(e Event) bool { return originMap[e] == "derived" }

// IsExtension reports whether the event is native to a subset of
// CLIs (extension event, e.g. Gemini-only or OpenCode-only).
func IsExtension(e Event) bool { return originMap[e] == "extension" }
`))

type tmplData struct {
	Timestamp string
	Version   string
	Events    []EventDef
}

func run() error {
	// Find repo root by walking up from executable working dir.
	root, err := findRoot()
	if err != nil {
		return fmt.Errorf("find repo root: %w", err)
	}

	specPath := filepath.Join(root, "spec", "events.yaml")
	data, err := os.ReadFile(specPath)
	if err != nil {
		return fmt.Errorf("read spec: %w", err)
	}

	var spec Spec
	if err := yaml.Unmarshal(data, &spec); err != nil {
		return fmt.Errorf("parse spec: %w", err)
	}

	if len(spec.Events) == 0 {
		return fmt.Errorf("no events found in %s", specPath)
	}

	outDir := filepath.Join(root, "internal", "events")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("create output dir: %w", err)
	}

	outPath := filepath.Join(outDir, "events_generated.go")

	td := tmplData{
		Timestamp: time.Now().UTC().Format(time.RFC3339),
		Version:   spec.Version,
		Events:    spec.Events,
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, td); err != nil {
		return fmt.Errorf("execute template: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt generated source: %w", err)
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		return fmt.Errorf("write output file: %w", err)
	}

	fmt.Fprintf(os.Stderr, "nerv-codegen: wrote %d events to %s\n", len(spec.Events), outPath)
	return nil
}

// findRoot locates the module root by looking for go.mod starting from cwd.
func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	return "", fmt.Errorf("go.mod not found")
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "nerv-codegen: %v\n", err)
		os.Exit(1)
	}
}

// camelize converts an event name to a Go PascalCase identifier suffix.
//   - PascalCase names pass through unchanged (e.g. "SessionStart").
//   - snake_case names become UpperCamelCase
//     (e.g. "inbox_message_added" → "InboxMessageAdded").
//
// Used by the template to keep wire-format event names (snake_case per
// the canonical naming rule, see docs/architecture/kit-bus-adoption.md
// §"Reserved" / US-0018) decoupled from Go identifier casing.
func camelize(name string) string {
	if !strings.ContainsRune(name, '_') {
		return name
	}
	parts := strings.Split(name, "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}
